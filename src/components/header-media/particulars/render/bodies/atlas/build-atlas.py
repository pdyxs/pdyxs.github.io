"""
Packs the Unity original's particle sprites into one atlas for the bodies layer.

Run from anywhere (needs Pillow with WebP), pointing at the Unity project:
    python3 -I build-atlas.py ~/dev/particulars/Assets
Writes atlas.webp and atlas-map.ts next to this file. Sources:
  Assets/Art/Game/Particles/Textures/NewDesigns/**      (particle layers, `<name><layer>[player].png`)
  Assets/Art/Game/GameObject/Textures/Spawner/big/*/    (spawn telegraph spinners)
  Assets/Art/Game/GameObject/Atlas/GameObjectAtlas.png  (s-white-ring-4 / s-black-ring-4, cropped)
"""
import hashlib, os, sys
from PIL import Image

CAP = 160      # largest sprite edge in the atlas, px
SPIN_CAP = 128
PAD = 6        # transparent gutter so mipmaps don't bleed between sprites
WIDTH = 2048

assets = os.path.expanduser(sys.argv[1])
out_dir = os.path.dirname(os.path.abspath(__file__))
sprites = {}

def add(name, img, cap):
    img = img.convert('RGBA')
    # Fully transparent pixels carry junk RGB in the originals; clear it so it compresses (and can't bleed).
    clear = Image.new('RGBA', img.size, (0, 0, 0, 0))
    img = Image.composite(img, clear, img.getchannel('A').point(lambda a: 255 if a else 0))
    if max(img.size) > cap:
        s = cap / max(img.size)
        img = img.resize((max(1, round(img.width * s)), max(1, round(img.height * s))), Image.LANCZOS)
    sprites[name] = img

nd = os.path.join(assets, 'Art/Game/Particles/Textures/NewDesigns')
for root, _, files in os.walk(nd):
    for f in files:
        if f.endswith('.png') and f != 'player glow.png':
            add(f[:-4], Image.open(os.path.join(root, f)), CAP)

spin = os.path.join(assets, 'Art/Game/GameObject/Textures/Spawner/big')
for par in ('white', 'black'):
    for i in range(1, 6):
        add(f's-{par}-spin-{i}', Image.open(os.path.join(spin, par, f'{par}-spin-{i}.png')), SPIN_CAP)
goa = Image.open(os.path.join(assets, 'Art/Game/GameObject/Atlas/GameObjectAtlas.png'))
add('s-white-ring-4', goa.crop((3758, 3680, 3758 + 64, 3680 + 64)), 64)
add('s-black-ring-4', goa.crop((3856, 3654, 3856 + 64, 3654 + 64)), 64)

# Dedupe identical pixels (e.g. matter and antimatter glows are the same image).
unique, alias = {}, {}
for name in sorted(sprites):
    h = hashlib.sha1(sprites[name].tobytes() + bytes(str(sprites[name].size), 'ascii')).hexdigest()
    if h in unique:
        alias[name] = unique[h]
    else:
        unique[h] = name

names = sorted(unique.values(), key=lambda n: (-sprites[n].height, n))
rects, x, y, shelf = {}, PAD, PAD, 0
for n in names:
    w, h = sprites[n].size
    if x + w + PAD > WIDTH:
        x, y, shelf = PAD, y + shelf + PAD, 0
    rects[n] = (x, y, w, h)
    x += w + PAD
    shelf = max(shelf, h)
height = 1
while height < y + shelf + PAD:
    height *= 2
atlas = Image.new('RGBA', (WIDTH, height), (0, 0, 0, 0))
for n, (x, y, w, h) in rects.items():
    atlas.paste(sprites[n], (x, y))
atlas.save(os.path.join(out_dir, 'atlas.webp'), 'WEBP', lossless=True, method=6)

with open(os.path.join(out_dir, 'atlas-map.ts'), 'w') as f:
    f.write('// Generated by build-atlas.py from the Unity original\'s sprites. Do not edit.\n')
    f.write(f'export const ATLAS_SIZE = {{ width: {WIDTH}, height: {height} }} as const;\n')
    f.write('/** Sprite name (the Unity atlas name) -> [x, y, width, height] in atlas pixels. */\n')
    f.write('export const ATLAS: Readonly<Record<string, readonly [number, number, number, number]>> = {\n')
    for n in sorted(sprites):
        r = rects[alias.get(n, n)]
        f.write(f"  '{n}': [{r[0]}, {r[1]}, {r[2]}, {r[3]}],\n")
    f.write('};\n')
print(len(sprites), 'sprites,', len(rects), 'unique, atlas', WIDTH, 'x', height)
