#!/usr/bin/env node
/**
 * Generates src/data/vimeo-posters.generated.ts — the poster (still frame) URL
 * for every Vimeo video referenced anywhere in src/content.
 *
 * Why generated: YouTube serves a poster at a predictable path, Vimeo doesn't.
 * Its only official route is an oEmbed call, and a build must not depend on a
 * third-party host being up. So the map is resolved here, committed, and read
 * as static data by embedPosterUrl (src/lib/embeds.ts).
 *
 * The fetch is incremental: an id already in the committed map is never
 * re-fetched, so an offline build (or a Vimeo outage) is a no-op rather than a
 * failure. Ids that fail to resolve are reported and left out — the gallery
 * falls back to a labelled tile.
 *
 * Run via `npm run generate:vimeo-posters` (a predev/prebuild step).
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CONTENT_DIR = join(ROOT, 'src/content');
const OUTPUT = join(ROOT, 'src/data/vimeo-posters.generated.ts');

/** Any vimeo.com or player.vimeo.com reference, in frontmatter or body. */
const VIMEO_REFERENCE = /https?:\/\/(?:www\.|player\.)?vimeo\.com\/(?:video\/)?(\d+)/g;

async function markdownFiles(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    // Mirrors CONTENT_GLOB_PATTERN: underscore-prefixed files and directories
    // are not content (templates, Obsidian config).
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await markdownFiles(path)));
    else if (entry.name.endsWith('.md')) found.push(path);
  }
  return found;
}

async function collectIds() {
  const ids = new Map(); // id -> first content file that referenced it
  for (const file of await markdownFiles(CONTENT_DIR)) {
    const text = await readFile(file, 'utf8');
    for (const match of text.matchAll(VIMEO_REFERENCE)) {
      if (!ids.has(match[1])) ids.set(match[1], relative(ROOT, file));
    }
  }
  return ids;
}

async function readExistingMap() {
  try {
    const source = await readFile(OUTPUT, 'utf8');
    const entries = [...source.matchAll(/'(\d+)':\s*'([^']+)'/g)];
    return new Map(entries.map(m => [m[1], m[2]]));
  } catch {
    return new Map();
  }
}

async function fetchPoster(id) {
  const endpoint = `https://vimeo.com/api/oembed.json?url=${encodeURIComponent(
    `https://vimeo.com/${id}`,
  )}`;
  const response = await fetch(endpoint, { signal: AbortSignal.timeout(10_000) });
  if (!response.ok) throw new Error(`oEmbed responded ${response.status}`);
  const body = await response.json();
  if (typeof body.thumbnail_url !== 'string') throw new Error('no thumbnail_url in response');
  return body.thumbnail_url;
}

const referenced = await collectIds();
const posters = await readExistingMap();

// Drop entries for videos no longer referenced, so the map can't accumulate
// posters for content that has been deleted.
for (const id of [...posters.keys()]) {
  if (!referenced.has(id)) posters.delete(id);
}

const missing = [...referenced.keys()].filter(id => !posters.has(id));
const failed = [];

for (const id of missing) {
  try {
    posters.set(id, await fetchPoster(id));
  } catch (error) {
    failed.push({ id, source: referenced.get(id), reason: error.message });
  }
}

const sorted = [...posters.entries()].sort((a, b) => a[0].localeCompare(b[0]));
const body = sorted.map(([id, url]) => `  '${id}': '${url}',`).join('\n');

await writeFile(
  OUTPUT,
  `// GENERATED by scripts/generate-vimeo-posters.mjs — do not edit.
//
// Vimeo poster (still frame) URLs, keyed by video id, for every Vimeo video
// referenced in src/content. Vimeo has no predictable poster path, so these
// come from its oEmbed API at build time. Re-run \`npm run generate:vimeo-posters\`
// after adding a Vimeo link; ids already present here are never re-fetched.
${
  failed.length > 0
    ? `//
// UNRESOLVED (poster fetch failed — these render a labelled tile instead):
${failed.map(f => `//   ${f.id} (${f.source}): ${f.reason}`).join('\n')}
`
    : ''
}
export const VIMEO_POSTERS: Record<string, string> = {
${body}${body ? '\n' : ''}};
`,
  'utf8',
);

console.log(
  `vimeo posters: ${sorted.length} resolved (${missing.length - failed.length} newly fetched)` +
    (failed.length > 0 ? `, ${failed.length} unresolved` : ''),
);
for (const f of failed) console.warn(`  unresolved ${f.id} (${f.source}): ${f.reason}`);
