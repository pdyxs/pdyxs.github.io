/**
 * Build step: regenerates src/data/lens-icons.generated.ts from the editable
 * SVG sources in src/icons/lenses/*.svg.
 *
 * Icons are authored as real SVG files (open them in Affinity Designer or
 * any vector editor) rather than hand-written IconShape data. This script
 * runs each one through svgo — flattening groups/transforms and converting
 * shape primitives (<circle>, <rect>, <line>, <polyline>, ...) into <path>
 * elements — then extracts the resulting path `d` strings into a typed
 * LensIconDef, which LensIcon.svelte renders as real declarative <path>
 * elements (see the "why structured shapes" note in src/lib/lens-icons.ts).
 *
 * "filled" vs "stroked" is read from the *source* file, not the svgo output:
 * a source whose root <svg> (or any shape) declares fill="none" is treated as
 * a stroked outline icon (the timelines, the flag); anything else is filled
 * (the default SVG fill is black, so an icon authored with plain filled
 * shapes and no stroke needs no special markup). This matches how a vector
 * editor naturally exports a stroke-only object vs a filled one.
 *
 * Run automatically before `npm run dev`/`build` via the "pre*" lifecycle
 * scripts, alongside generate-lens-registry.mjs. Safe to run manually:
 *   node scripts/generate-lens-icons.mjs
 */

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { optimize } from 'svgo';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC_DIR = path.resolve(__dirname, '../src/icons/lenses');
const OUT_PATH = path.resolve(__dirname, '../src/data/lens-icons.generated.ts');

const SVGO_PLUGINS = [
  'preset-default',
  { name: 'convertShapeToPath', params: { convertArcs: true } },
];

async function collectIcons() {
  let files;
  try {
    files = (await readdir(SRC_DIR)).filter(f => f.endsWith('.svg'));
  } catch {
    return [];
  }
  files.sort();

  const icons = [];
  for (const file of files) {
    const key = file.slice(0, -'.svg'.length);
    const raw = await readFile(path.join(SRC_DIR, file), 'utf-8');

    // A source with an explicit fill="none" is a stroked outline icon;
    // everything else falls back to SVG's default fill (filled).
    const filled = !/fill\s*[:=]\s*["']?none["']?/i.test(raw);

    const { data: optimized } = optimize(raw, { multipass: true, plugins: SVGO_PLUGINS });

    const shapes = [...optimized.matchAll(/<path[^>]*\bd="([^"]+)"/g)].map(m => ({
      kind: 'path',
      d: m[1],
    }));

    if (shapes.length === 0) {
      throw new Error(`lens-icons: ${file} produced no <path> data after svgo optimisation`);
    }

    icons.push({ key, filled, shapes });
  }
  return icons;
}

async function main() {
  const icons = await collectIcons();

  const entries = icons
    .map(({ key, filled, shapes }) => {
      const shapesLiteral = shapes
        .map(s => `      { kind: 'path', d: ${JSON.stringify(s.d)} }`)
        .join(',\n');
      return `  ${JSON.stringify(key)}: {\n    filled: ${filled},\n    shapes: [\n${shapesLiteral},\n    ],\n  }`;
    })
    .join(',\n');

  const body = `// AUTO-GENERATED by scripts/generate-lens-icons.mjs — do not edit by hand.
// Source: src/icons/lenses/*.svg. Regenerated on predev/prebuild.
import type { LensIconDef } from '../lib/lens-icons.ts';

export const LENS_ICON_DEFS: Record<string, LensIconDef> = {
${entries}
};
`;

  await mkdir(path.dirname(OUT_PATH), { recursive: true });
  await writeFile(OUT_PATH, body, 'utf-8');
  console.log(`lens-icons: ${icons.length} icons -> src/data/lens-icons.generated.ts`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
